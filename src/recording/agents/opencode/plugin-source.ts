/**
 * Version of the JSONL record format written by the generated plugin. Bump it
 * whenever the plugin source changes so existing installs are flagged as stale.
 */
export const OPENCODE_PLUGIN_SCHEMA_VERSION = 1;

/** Repo-relative path of the generated plugin (OpenCode auto-loads `.opencode/plugins/*.ts`). */
export const OPENCODE_PLUGIN_RELATIVE_PATH = ".opencode/plugins/flight-recorder.ts";

/** Repo-relative path of the JSONL log the plugin appends to. */
export const OPENCODE_LOG_RELATIVE_PATH = ".opencode/flight-recorder-events.jsonl";

const SCHEMA_MARKER = "flight-recorder-plugin-schema:";

/** Reads the schema version embedded in an installed plugin's source, or null if it is not a Flight Recorder plugin. */
export function readOpenCodePluginSchemaVersion(source: string): number | null {
  const match = new RegExp(`${SCHEMA_MARKER} (\\d+)`).exec(source);
  return match ? Number(match[1]) : null;
}

/**
 * Builds the source of the OpenCode (>= 2.0) plugin that records tool calls
 * and step snapshots for one repository as JSONL. The log path is derived
 * from the plugin's own location, and step events are filtered to sessions
 * running inside `repoRoot`, because one OpenCode service hosts all projects.
 */
export function buildOpenCodePluginSource(repoRoot: string): string {
  return `// Generated by the Flight Recorder VS Code extension. Do not edit.
// ${SCHEMA_MARKER} ${OPENCODE_PLUGIN_SCHEMA_VERSION}
// Records OpenCode tool calls and step snapshots for research on AI coding
// assistants. Re-run "Flight Recorder: Configure OpenCode Plugin" to update.
import { appendFileSync } from "node:fs"
import { fileURLToPath } from "node:url"

const SCHEMA = ${OPENCODE_PLUGIN_SCHEMA_VERSION}
const REPO_ROOT = ${JSON.stringify(repoRoot)}
const LOG = fileURLToPath(new URL("../flight-recorder-events.jsonl", import.meta.url))
// Only these tools keep their full output; others (read, glob, ...) would bloat the log.
const FULL_PAYLOAD_TOOLS = new Set(["edit", "write", "patch", "shell", "execute"])

function record(kind, fields) {
  try {
    appendFileSync(LOG, JSON.stringify({ fr: SCHEMA, ts: Date.now(), kind, ...fields }) + "\\n")
  } catch {
    // Recording must never break the agent.
  }
}

function insideRepo(directory) {
  return typeof directory === "string" &&
    (directory === REPO_ROOT || directory.startsWith(REPO_ROOT + "/") || directory.startsWith(REPO_ROOT + "\\\\"))
}

function call(e) {
  return { tool: e.tool, sessionID: e.sessionID, messageID: e.messageID, callID: e.id, agent: e.agent, input: e.input }
}

export default {
  id: "flight-recorder",
  setup: async (ctx) => {
    record("setup", { app: ctx.app, directory: ctx.location?.directory })

    await ctx.tool.hook("execute.before", (e) => {
      try {
        record("pre", call(e))
      } catch {}
    })

    await ctx.tool.hook("execute.after", (e) => {
      try {
        const full = FULL_PAYLOAD_TOOLS.has(e.tool)
        if (e.status === "completed") {
          record("post", {
            ...call(e),
            status: "completed",
            output: full ? e.result?.output : undefined,
            metadata: full ? e.result?.metadata : undefined,
          })
        } else {
          record("post", { ...call(e), status: "error", error: e.error?.message, metadata: full ? e.error?.metadata : undefined })
        }
      } catch {}
    })

    const abort = new AbortController()
    ;(async () => {
      try {
        for await (const ev of ctx.event.subscribe({ types: ["session.step.ended"], signal: abort.signal })) {
          if (ev.type !== "session.step.ended" || !insideRepo(ev.location?.directory)) continue
          const data = ev.data ?? {}
          if (!Array.isArray(data.files) || data.files.length === 0) continue
          record("step", { sessionID: data.sessionID, messageID: data.assistantMessageID, files: data.files, snapshot: data.snapshot })
        }
      } catch {}
    })()

    return () => abort.abort()
  },
}
`;
}
